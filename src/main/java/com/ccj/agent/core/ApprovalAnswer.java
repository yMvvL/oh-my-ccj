package com.ccj.agent.core;

/**
 * 审批请求得到的答复，是五种答案，不是两种。
 *
 * <p>它取代的那个布尔值把所有答案都逼成是或否，而想说「别再问这个了」的唯一办法是把整个会话的审批关掉——
 * 那正是人们跑 `--yolo` 的原因。「这一次可以」和「一直可以」是后果不同的两种答复，调用方必须能区分它们，
 * 所以它们是各自独立的值；「这一次不行」和「以后都不行」同理。
 */
public enum ApprovalAnswer {

  /** 照做，下次再问一遍。 */
  ALLOW_ONCE,

  /** 照做，本会话内对同一条命令或同一个路径不再询问。 */
  ALLOW_SESSION,

  /** 照做，并写入一条规则，使本项目内永远不再询问。 */
  ALLOW_ALWAYS,

  /** 被人拒绝，就这一次。 */
  DENY,

  /**
   * 被人拒绝，并写入一条拒绝规则，使本项目内同样的调用从此不再询问。
   *
   * <p>与 {@link #ALLOW_ALWAYS} 对称：那个写下一条规则回答「可以」，这个写下一条规则回答「不行」，两者写进
   * 同一个文件，主语也一模一样。没有它的时候，被一个反复出现的提示烦到的人只有一条出路——把整个会话的审批
   * 关掉，而那正是这道关卡存在时要防的事。
   */
  DENY_ALWAYS,

  /**
   * 被用户先前写下的规则拒绝，没有问过任何人。
   *
   * <p>与 {@link #DENY} 区分开，因为两者在转录里的读法不同：一个是「我刚才说了不行」，另一个是「你写的
   * 一条规则说不行」——只有后者值得去翻出来看。
   */
  DENY_BY_RULE;

  public boolean allowed() {
    return this == ALLOW_ONCE || this == ALLOW_SESSION || this == ALLOW_ALWAYS;
  }

  /** 答案为否时，工具交还给模型的内容。 */
  public String refusal() {
    return switch (this) {
      // 两种「不行」都指向同一份文件，因为改它就是恢复询问的办法。写的是它的名字而不是某个展开后的路径：
      // 主目录是应用主目录，`--home` 和 CCJ_HOME 都能移动它，而这个枚举拿不到本次运行用的是哪一个。
      case DENY_BY_RULE ->
          "被审批文件中的某条规则拒绝（可运行 ccj --help、查看 SECURITY.md 了解如何改规则）："
              + "那条规则写在应用主目录下的 approvals.json 里，删掉它就能恢复询问";
      case DENY_ALWAYS ->
          "被用户拒绝，并已写入一条拒绝规则：今后同样的调用由应用主目录下的 approvals.json 里那条规则挡下，"
              + "删掉它就能恢复询问";
      default -> "被用户拒绝";
    };
  }
}
